"""Engine-agnostic scenario runner for the dbmigrate family.

A task's scenario.json (generated by iacctl from spec.json and the task type's template; never hand-written) lists
scenarios. Each loads a snapshot into a private database server, then runs operations: the submission's migration tool
(upgrade/downgrade to a target, update-to-tag, rollback, validate), the old and new applications' query corpora, the
grader's write traffic between steps, data invariants, catalog requirements and lock rules. In record mode (the
reference solution, at build time) every comparable output is stored as the expected value; in grade mode the
submission's outputs are compared with them.
"""
import json
import os
import re
import shutil
import time
from pathlib import Path

from dbm_util import error_digest, canon, chown_tree, debug, is_root, say, sha256_file, short, tail, user_ids


class StopGrading(Exception):
    pass


# ---- query corpora --------------------------------------------------------------------------------------------------
HEADER = re.compile(r"^--\s*(name|mode|params|note|set)\s*:\s*(.*?)\s*$", re.I)


def parse_corpus(path):
    """aiosql-style query files: `-- name: x`, then `-- mode: read|write` and zero or more `-- params: {json}` lines,
    then the statement (pyformat placeholders %(name)s). Several queries may share a file. Order = file name order,
    then position in the file."""
    out = []
    files = sorted(Path(path).rglob("*.sql")) if Path(path).is_dir() else [Path(path)]
    for f in files:
        cur = None
        for line in f.read_text().splitlines():
            m = HEADER.match(line)
            if m and m.group(1).lower() == "name":
                if cur:
                    out.append(cur)
                cur = {"name": m.group(2), "mode": "read", "params": [], "sql_lines": [], "file": f.name}
                continue
            if cur is None:
                continue
            if m and not cur["sql_lines"]:
                key, val = m.group(1).lower(), m.group(2)
                if key == "mode":
                    cur["mode"] = val.lower()
                elif key == "params":
                    cur["params"].append(json.loads(val))
                elif key == "set":
                    cur["settings"] = json.loads(val)
                continue
            cur["sql_lines"].append(line)
        if cur:
            out.append(cur)
    for q in out:
        sql = "\n".join(q.pop("sql_lines")).strip()
        q["sql"] = re.sub(r";\s*$", "", sql)
        if not q["params"]:
            q["params"] = [{}]
    names = [q["name"] for q in out]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise RuntimeError(f"duplicate query names in {path}: {dup}")
    return out


# ---- comparisons ----------------------------------------------------------------------------------------------------
def same_outcome(exp, got):
    """Whether a statement's outcome matches the reference: rows and row counts exactly, or an error of the same
    SQLSTATE class when the reference statement failed."""
    if "error" in exp:
        return "error" in got and str(got["error"])[:2] == str(exp["error"])[:2]
    if "error" in got:
        return False
    if exp.get("rows") is not None:
        return got.get("rows") == exp["rows"] and (got.get("columns") == exp.get("columns"))
    return got.get("rowcount") == exp.get("rowcount")


def describe(outcome):
    if outcome is None:
        return "nothing"
    if "error" in outcome:
        return f"error {outcome['error']} ({outcome.get('message', '')[:120]})"
    if outcome.get("rows") is not None:
        return f"{len(outcome['rows'])} row(s) {short(outcome['rows'], 160)}"
    return f"rowcount {outcome.get('rowcount')}"


# ---- catalog requirements -------------------------------------------------------------------------------------------
def _cols_match(want, got):
    return [c.lower() for c in want] == [c.lower() for c in got]


def check_requirement(req, cat, norm_type):
    """One catalog requirement (a table/view entry of the spec) against a normalized catalog -> list of problems."""
    probs = []
    if "view" in req:
        name = req["view"]
        present = name in cat["views"]
        if req.get("exists", True) and not present:
            probs.append(f"view {name} is missing")
        if not req.get("exists", True) and present:
            probs.append(f"view {name} must not exist")
        return probs
    name = req["table"]
    t = cat["tables"].get(name)
    if not req.get("exists", True):
        if t is not None or name in cat["views"]:
            probs.append(f"{name} must not exist any more")
        return probs
    if t is None:
        return [f"table {name} is missing"]
    for col, spec in (req.get("columns") or {}).items():
        c = t["columns"].get(col)
        if c is None:
            probs.append(f"{name}.{col} is missing")
            continue
        if isinstance(spec, str):
            spec = {"type": spec}
        if spec.get("type") and norm_type(spec["type"]) != norm_type(c["type"]):
            probs.append(f"{name}.{col} has type {c['type']}, want {spec['type']}")
        if "not_null" in spec and bool(spec["not_null"]) != c["not_null"]:
            probs.append(f"{name}.{col} {'must' if spec['not_null'] else 'must not'} be NOT NULL")
        if "default" in spec:
            want = spec["default"]
            got = c["default"]
            if (want is None) != (got is None) or (want is not None and re.sub(r"\s+", " ", str(want)).lower()
                                                    not in re.sub(r"\s+", " ", str(got)).lower()):
                probs.append(f"{name}.{col} default is {got!r}, want {want!r}")
    for col in req.get("absent_columns") or []:
        if col in t["columns"]:
            probs.append(f"{name}.{col} must be dropped")
    cons = cat["constraints"].get(name, [])
    if "primary_key" in req:
        pk = [c for c in cons if c["type"] == "primary_key"]
        if not pk or not _cols_match(req["primary_key"], pk[0]["columns"]):
            probs.append(f"{name} primary key is {pk[0]['columns'] if pk else None}, want {req['primary_key']}")
    for u in req.get("unique") or []:
        cols = u["columns"] if isinstance(u, dict) else u
        hit = [c for c in cons if c["type"] in ("unique", "primary_key") and _cols_match(cols, c["columns"])]
        uidx = [i for i in cat["indexes"].get(name, []) if i["unique"] and i["valid"] and i["predicate"] is None
                and _cols_match(cols, i["columns"])]
        need_constraint = isinstance(u, dict) and u.get("constraint", False)
        if not hit and (need_constraint or not uidx):
            probs.append(f"{name} needs a {'UNIQUE constraint' if need_constraint else 'unique constraint or index'} "
                         f"on ({', '.join(cols)})")
    for fk in req.get("foreign_keys") or []:
        hit = [c for c in cons if c["type"] == "foreign_key" and _cols_match(fk["columns"], c["columns"])
               and (c["references"] or "").lower() == fk["references"].lower()
               and _cols_match(fk.get("ref_columns", c["ref_columns"]), c["ref_columns"])]
        if not hit:
            probs.append(f"{name} needs a foreign key ({', '.join(fk['columns'])}) -> {fk['references']}")
            continue
        if fk.get("name") and not any(c["name"].lower() == fk["name"].lower() for c in hit):
            probs.append(f"{name} foreign key ({', '.join(fk['columns'])}) must be named {fk['name']} "
                         f"(is {hit[0]['name']})")
        c = hit[0]
        if "on_delete" in fk and c["on_delete"] != fk["on_delete"].lower():
            probs.append(f"{name} foreign key ({', '.join(fk['columns'])}) is ON DELETE {c['on_delete']}, "
                         f"want {fk['on_delete']}")
        if fk.get("validated", True) and not c["validated"]:
            probs.append(f"{name} foreign key ({', '.join(fk['columns'])}) is still NOT VALID")
    for chk in req.get("checks") or []:
        hit = [c for c in cons if c["type"] == "check" and all(s.lower() in c["definition"].lower()
                                                               for s in chk.get("contains", []))]
        if not hit:
            probs.append(f"{name} needs a CHECK constraint {chk.get('describe') or chk.get('contains')}")
        elif chk.get("name") and not any(c["name"].lower() == chk["name"].lower() for c in hit):
            probs.append(f"{name} CHECK {chk.get('describe') or chk.get('contains')} must be named {chk['name']} "
                         f"(is {hit[0]['name']})")
        elif chk.get("validated", True) and not any(c["validated"] for c in hit):
            probs.append(f"{name} CHECK {chk.get('describe') or chk.get('contains')} is still NOT VALID")
    for ix in req.get("indexes") or []:
        hit = [i for i in cat["indexes"].get(name, []) if _cols_match(ix["columns"], i["columns"])
               and (("unique" not in ix) or i["unique"] == ix["unique"])
               and (("method" not in ix) or i["method"] == ix["method"])
               and (("where_contains" not in ix) or (i["predicate"] and ix["where_contains"].lower()
                                                      in i["predicate"].lower()))]
        if not hit:
            probs.append(f"{name} needs an index on ({', '.join(ix['columns'])})")
        elif ix.get("name") and not any(i["name"].lower() == ix["name"].lower() for i in hit):
            probs.append(f"{name} index on ({', '.join(ix['columns'])}) must be named {ix['name']} (is {hit[0]['name']})")
        elif not any(i["valid"] for i in hit):
            probs.append(f"{name} index on ({', '.join(ix['columns'])}) is INVALID (a failed concurrent build)")
    if req.get("no_triggers") and cat["triggers"].get(name):
        probs.append(f"{name} still has trigger(s) {[t_['name'] for t_ in cat['triggers'][name]]}")
    if req.get("no_invalid_indexes", True):
        bad = [i["name"] for i in cat["indexes"].get(name, []) if not i["valid"]]
        if bad:
            probs.append(f"{name} has INVALID index(es) {bad}")
    if "rls" in req and bool(req["rls"]) != t["rls"]:
        probs.append(f"{name} row level security must be {'enabled' if req['rls'] else 'disabled'}")
    if "partitioned_by" in req:
        if t["kind"] != "p" or req["partitioned_by"].lower() not in (t["partition_key"] or "").lower():
            probs.append(f"{name} must be partitioned by {req['partitioned_by']}")
    if "partitions_min" in req:
        parts = [k for k, v in cat["tables"].items() if v.get("partition_of") == name]
        if len(parts) < int(req["partitions_min"]):
            probs.append(f"{name} has {len(parts)} partitions, want at least {req['partitions_min']}")
        if req.get("default_partition") and not any((cat["tables"][k].get("partition_bound") or "").upper() == "DEFAULT"
                                                    for k in parts):
            probs.append(f"{name} needs a DEFAULT partition")
    return probs


def strip_tables(cat, skip):
    """A catalog without some tables (the migration tool's own history tables in parity checks)."""
    if not skip:
        return cat
    low = {t.lower() for t in skip}
    out = dict(cat)
    for key in ("tables", "constraints", "indexes", "triggers"):
        out[key] = {k: v for k, v in (cat.get(key) or {}).items() if k.lower() not in low}
    return out


def catalog_diff(base, now, limit=12):
    """Differences between two normalized catalogs (downgrade must restore the starting schema)."""
    out = []

    def walk(a, b, path):
        if len(out) >= limit:
            return
        if isinstance(a, dict) and isinstance(b, dict):
            for k in sorted(set(a) | set(b)):
                if k in ("column_order",):
                    continue
                if k not in a:
                    out.append(f"{path}/{k}: added")
                elif k not in b:
                    out.append(f"{path}/{k}: removed")
                else:
                    walk(a[k], b[k], f"{path}/{k}")
            return
        if isinstance(a, list) and isinstance(b, list):
            ka = sorted(canon(x) for x in a)
            kb = sorted(canon(x) for x in b)
            if ka != kb:
                extra = [x for x in kb if x not in ka][:2]
                gone = [x for x in ka if x not in kb][:2]
                out.append(f"{path}: " + "; ".join([*(f"added {short(x, 140)}" for x in extra),
                                                     *(f"removed {short(x, 140)}" for x in gone)]))
            return
        if a != b:
            out.append(f"{path}: {short(a, 80)} -> {short(b, 80)}")
    walk(base, now, "")
    return out


# ---- the runner -----------------------------------------------------------------------------------------------------
class Grading:
    """Collects gates and checks, then computes the reward."""

    def __init__(self, fast_fail=False):
        self.gates, self.checks = {}, {}
        self.core = set()
        self.fast_fail = fast_fail

    def gate(self, name, ok, detail=""):
        if name in self.gates and not self.gates[name]["ok"]:
            return
        self.gates[name] = {"ok": bool(ok), "detail": str(detail)[:300], "skipped": False}
        say(f"GATE {name}: {'ok' if ok else 'FAILED'}{(' - ' + str(detail)[:300]) if detail and not ok else ''}")
        if not ok and self.fast_fail:
            raise StopGrading(name)

    def check(self, name, ok, detail="", core=False):
        self.checks[name] = {"ok": bool(ok), "detail": str(detail)[:300]}
        if core:
            self.core.add(name)
        say(f"CHECK {name}: {'ok' if ok else 'FAILED'}{(' - ' + str(detail)[:300]) if detail and not ok else ''}")
        # fast_fail True: stop at the first failure (enough to know reward < 1); "core": stop only once the reward is
        # certainly 0 (a gate or a core check failed), so an expected-zero case is never cut short at a partial score
        if not ok and self.fast_fail and (self.fast_fail != "core" or core):
            raise StopGrading(name)

    def reward(self):
        if any(not g["ok"] for g in self.gates.values()):
            return 0.0
        if any(not self.checks[c]["ok"] for c in self.core if c in self.checks):
            return 0.0
        total = len(self.checks)
        passed = sum(1 for c in self.checks.values() if c["ok"])
        if total == 0:
            return 0.0
        return 1.0 if passed == total else 0.0  # binary grading (SRE-xai-ots spec): every check or nothing


class Runner:
    def __init__(self, scenario, trusted_repo, submission, workdir, snapshots, mode="grade", expected=None,
                 port=5432, server_user=None, solver_user=None, fast_fail=False, only=None):
        self.sc = scenario
        self.trusted = Path(trusted_repo)
        self.sub = Path(submission)
        self.work = Path(workdir)
        self.snapshots = Path(snapshots)
        self.mode = mode
        self.expected = expected or {}
        self.recorded = {}
        self.port = port
        self.server_user = server_user if is_root() else None
        self.solver_user = solver_user if (is_root() and solver_user and user_ids(solver_user)) else None
        self.g = Grading(fast_fail)
        self.only = only
        self.shared = {}
        self.corpora = {name: parse_corpus(self.trusted / c["path"]) for name, c in scenario.get("corpora", {}).items()}

    # -- engine / tool factories (engine modules are imported lazily: an image carries one engine) --
    def engine(self, root):
        from dbm_snapshot import make_engine
        db = self.sc["database"]
        return make_engine(self.sc["engine"], root, self.port, self.server_user, db["name"], db["role"],
                           db["password"])

    def norm_type(self):
        if self.sc["engine"] == "postgres16":
            from dbm_pg import norm_type
            return norm_type
        from dbm_mysql import norm_type
        return norm_type

    # -- gates on the submission's files --
    def file_gates(self):
        if not self.sub.is_dir() or not any(self.sub.iterdir()):
            self.g.gate("submission_present", False, f"no repository at {self.sub}")
            return False
        self.g.gate("submission_present", True)
        changed = []
        for rel in self.sc.get("frozen", []):
            a, b = self.trusted / rel, self.sub / rel
            if not b.exists():
                changed.append(f"{rel} (deleted)")
            elif a.is_file() and sha256_file(a) != sha256_file(b):
                changed.append(rel)
        for pat in self.sc.get("forbidden_paths", []):
            hits = [str(p.relative_to(self.sub)) for p in self.sub.glob(pat)]
            changed += [f"{h} (not allowed)" for h in hits]
        self.g.gate("frozen_files", not changed, "changed: " + ", ".join(changed[:8]) if changed else "")
        bad = []
        for rule in self.sc.get("forbidden_patterns", []):
            rx = re.compile(rule["regex"], re.I | re.S)
            for f in sorted(self.sub.glob(rule.get("glob", "**/*"))):
                if f.is_file() and f.stat().st_size < 4_000_000 and rx.search(f.read_text(errors="replace")):
                    bad.append(f"{f.relative_to(self.sub)}: {rule['why']}")
        if self.sc.get("forbidden_patterns"):
            self.g.gate("forbidden_constructs", not bad, "; ".join(bad[:4]))
        return not changed and not bad

    # -- one scenario --
    def run_scenario(self, scen):
        name = scen["name"]
        root = self.work / name
        if root.exists():
            shutil.rmtree(root)
        root.mkdir(parents=True)
        os.chmod(root, 0o755)
        say(f"scenario {name}: snapshot {scen['snapshot']}")
        eng = self.engine(root / "db")
        snap = self.snapshots / scen["snapshot"]
        locks = any(op.get("locks") for op in scen["ops"])
        eng.decode_writes = locks and "batched_writes" in ((self.sc.get("lock_rules") or {}).get("rules") or [])
        eng.restore(snap)
        eng.start()
        try:
            if locks:
                eng.instrument()
            from dbm_tools import make_tool, prepare_repo
            repo = prepare_repo(self.sub, root / "repo", self.solver_user)
            tool = make_tool(self.sc["tool"], repo, eng, self.sc.get("tool_config"), self.solver_user)
            state = {"evidence": [], "baseline_catalog": None, "failed_migration": None, "baseline_rel": None}
            if any(op["op"] == "table_data" for op in scen["ops"]):
                # the tables that exist before anything runs, with their primary keys (the submission cannot
                # influence this list)
                cat = eng.catalog()
                state["start_tables"] = {}
                for t in sorted(cat["tables"]):
                    if "." in t:
                        continue
                    cols = cat["tables"][t]["columns"]
                    # values the database generates (serial / identity / AUTO_INCREMENT keys): which row gets which
                    # value depends on insertion order, which MIGRATION_SPEC.md never fixes, so they are not compared
                    auto = [k for k, v in cols.items() if v.get("identity") or v.get("generated")
                            or str(v.get("default") or "").lower().startswith("nextval(")]
                    state["start_tables"][t] = {
                        "columns": [k for k in (cat["tables"][t].get("column_order") or sorted(cols)) if k not in auto],
                        "types": {k: v.get("type") for k, v in cols.items()}}
            for op in scen["ops"]:
                self.run_op(scen, op, eng, tool, state)
        finally:
            eng.stop()

    def key(self, scen, op):
        return f"{scen['name']}.{op['id']}"

    def store(self, scen, op, value):
        self.recorded[self.key(scen, op)] = value

    def want(self, scen, op):
        return self.expected.get(self.key(scen, op))

    def is_core(self, scen, op):
        return bool(op.get("core"))

    def run_op(self, scen, op, eng, tool, state):
        kind = op["op"]
        label = self.key(scen, op)
        blocked = state["failed_migration"]
        if blocked and kind not in ("locks",):
            if kind in ("queries", "traffic", "invariants", "catalog", "assert_revision", "rollback", "migrate",
                        "validate", "status", "idempotent", "table_data"):
                if op.get("check", True) and kind not in ("catalog_capture",):
                    for name in self.check_names(scen, op):
                        self.g.check(name, False, f"not graded: {blocked}", core=self.is_core(scen, op))
            return
        t0 = time.time()
        if kind == "catalog_publish":
            self.shared[f"catalog:{op['as']}"] = eng.catalog()
            return
        if kind == "history_capture":
            state["history_before"] = eng.changelog_state(self.sc.get("tool_config", {}).get("changelog_table",
                                                                                              "DATABASECHANGELOG"))
            return
        if kind == "history_check":
            ok, detail = self.history_check(eng, state)
            if self.mode == "record" and not ok:
                raise RuntimeError(f"reference solution: {label}: {detail}")
            self.g.check(label, ok, detail, core=self.is_core(scen, op))
            return
        if kind == "catalog_capture":
            cat = eng.catalog()
            if op.get("as"):
                state.setdefault("captures", {})[op["as"]] = cat
                if op.get("publish"):
                    self.shared[f"catalog:{op['as']}"] = cat
                return
            state["baseline_catalog"] = cat
            state["baseline_rel"] = eng.relfiles_by_oid() if hasattr(eng, "relfiles_by_oid") else None
            state["baseline_tables"] = set(state["baseline_catalog"]["tables"])
            return
        if kind == "stamp":
            res = tool.stamp(op["target"])
            ok = res.ok and not res.leftovers
            why = f"`{tool.name} stamp {op['target']}` failed (exit {res.code}): {error_digest(res.output, 6)}" if not ok else ""
            if self.mode == "record" and not ok:
                raise RuntimeError(f"reference solution: {why}")
            if op.get("gate"):
                self.g.gate(op.get("gate_name", "stamp"), ok, why)
            else:
                self.g.check(label, ok, why, core=self.is_core(scen, op))
            if not ok:
                state["failed_migration"] = f"{op['id']} failed"
            return
        if kind == "assert_revision":
            cur = tool.current()
            if self.mode == "record":
                self.store(scen, op, cur)
                return
            want = op.get("expect") or self.want(scen, op)

            def canon_ids(ids):  # numbered versions (golang-migrate): 0190 and 190 are the same version
                return [str(int(x)) if isinstance(x, (int, str)) and str(x).isdigit() else x for x in (ids or [])]
            ok = canon_ids(cur) == canon_ids(want)
            if op.get("gate"):
                self.g.gate(op.get("gate_name", "starting_revision"), ok, f"database is at {cur}, want {want}")
            else:
                self.g.check(label, ok, f"database is at {cur}, want {want}", core=self.is_core(scen, op))
            return
        if kind == "migrate":
            before = eng.lock_snapshot() if op.get("locks") else None
            mark = eng.log_mark() if op.get("locks") else None
            res = tool.migrate(op["target"])
            debug(f"{label}: exit {res.code} in {time.time() - t0:.1f}s\n{tail(res.output, 20)}")
            if op.get("locks"):
                end = eng.log_mark()
                after = eng.lock_snapshot()
                state["evidence"].append(eng.collect_evidence(op["id"], before, after, mark, end,
                                                              state.get("baseline_rel")))
            say(f"{label}: {tool.name} {op.get('verb', 'upgrade')} {op['target']} -> exit {res.code} "
                f"({time.time() - t0:.0f}s)")
            ok = res.ok and not res.leftovers
            why = (f"`{tool.name} {op.get('verb', 'upgrade')} {op['target']}` failed (exit {res.code}): "
                   f"{error_digest(res.output, 6)}" if not res.ok else
                   f"the migration left {res.leftovers} process(es) running" if res.leftovers else "")
            if self.mode == "record" and not ok:
                raise RuntimeError(f"reference solution: {why}")
            if op.get("gate"):
                self.g.gate(op.get("gate_name", "migrations_apply"), ok, f"{op['id']}: {why}")
            elif op.get("check", True):
                self.g.check(label, ok, why, core=self.is_core(scen, op))
            if not ok:
                state["failed_migration"] = f"{op['id']} failed"
            return
        if kind == "rollback":
            res = tool.rollback(op["target"])
            say(f"{label}: {tool.name} rollback {op['target']} -> exit {res.code} ({time.time() - t0:.0f}s)")
            ok = res.ok and not res.leftovers
            why = f"rollback to {op['target']} failed (exit {res.code}): {error_digest(res.output, 6)}" if not ok else ""
            if self.mode == "record" and not ok:
                raise RuntimeError(f"reference solution: {why}")
            self.g.check(label, ok, why, core=self.is_core(scen, op))
            if not ok:
                state["failed_migration"] = f"{op['id']} failed"
            return
        if kind in ("queries", "traffic"):
            if kind == "queries":
                items = [(q, i, p) for q in self.corpora[op["corpus"]] if q["mode"] == op.get("mode", "read")
                         for i, p in enumerate(q["params"])]
            else:
                by_name = {(c, q["name"]): q for c, qs in self.corpora.items() for q in qs}
                items = []
                for i, t in enumerate(self.sc.get("traffic", {}).get(op["plan"], [])):
                    q = by_name.get((t["corpus"], t["query"]))
                    if q is None:
                        raise RuntimeError(f"traffic plan {op['plan']} names unknown query {t['corpus']}.{t['query']}")
                    items.append((q, i, t.get("params", {})))
            conn = eng.app_session()
            try:
                outs = []
                for q, i, p in items:
                    p = dict(p) if isinstance(p, dict) else p
                    settings = {**(q.get("settings") or {}), **(p.pop("__set__", {}) if isinstance(p, dict) and "__set__" in p else {})}
                    outs.append(eng.run_statement(conn, q["sql"], p, read_only=(q["mode"] == "read"),
                                                  settings=settings or None))
            finally:
                conn.close()
            keys = [f"{q['name']}#{i}" for q, i, _ in items]
            if self.mode == "record":
                self.store(scen, op, dict(zip(keys, outs)))
                bad = [k for k, o in zip(keys, outs) if "error" in o and not op.get("errors_ok")]
                if bad and kind == "queries":
                    raise RuntimeError(f"reference solution: {label}: queries failed: "
                                       + "; ".join(f"{k}: {describe(o)}" for k, o in zip(keys, outs) if "error" in o)[:600])
                return
            want = self.want(scen, op) or {}
            wrong = [(k, want.get(k), o) for k, o in zip(keys, outs) if k not in want or not same_outcome(want[k], o)]
            detail = "; ".join(f"{k}: expected {describe(w)}, got {describe(o)}" for k, w, o in wrong[:3])
            if len(wrong) > 3:
                detail += f"; ... {len(wrong)} of {len(keys)} statements differ"
            self.g.check(label, not wrong, detail, core=self.is_core(scen, op))
            return
        if kind == "table_data":
            # every table that existed at the start, in every start column the reference still has at the end (the
            # reference's record fixes that column list; generated key values aside): the same multiset of rows.
            # Tables the reference dropped or renamed carry no expectation here (the catalog checks judge them).
            skip = {t.lower() for t in op.get("skip", [])}
            start = {t: v for t, v in (state.get("start_tables") or {}).items() if t.lower() not in skip}
            if self.mode == "record":
                end_tables = eng.catalog()["tables"]
                outs = {}
                for t, info in start.items():
                    if t not in end_tables:
                        outs[t] = {"columns": None}
                        continue
                    cols = [col for col in info["columns"] if col in end_tables[t]["columns"]]
                    outs[t] = {"columns": cols, "result": eng.content_checksum(t, cols, info["types"])}
                self.store(scen, op, outs)
                bad = [k for k, o in outs.items() if o.get("result") and "error" in o["result"]]
                if bad:
                    raise RuntimeError(f"reference solution: {label}: table(s) {bad} cannot be read: "
                                       + "; ".join(describe(outs[k]["result"]) for k in bad)[:400])
                return
            want = self.want(scen, op) or {}
            wrong = []
            for t, w in sorted(want.items()):
                if w.get("columns") is None:
                    continue
                got = eng.content_checksum(t, w["columns"], (start.get(t) or {}).get("types"))
                if not same_outcome(w["result"], got):
                    wrong.append((t, w["result"], got))
            detail = "; ".join(f"table {k}: expected {describe(w)}, got {describe(o)}" for k, w, o in wrong[:3])
            self.g.check(label, not wrong, ("rows or values differ from the reference (data lost or changed): " + detail)
                         if wrong else "", core=self.is_core(scen, op))
            return
        if kind == "invariants":
            outs = {}
            with eng.admin() as c:
                c.autocommit = True
                for inv in self.sc.get("invariants", {}).get(op["set"], []):
                    outs[inv["name"]] = eng.run_statement(c, inv["sql"], None, read_only=True, timeout_ms=120000)
            if self.mode == "record":
                self.store(scen, op, outs)
                bad = [k for k, o in outs.items() if "error" in o]
                if bad:
                    raise RuntimeError(f"reference solution: invariant(s) {bad} failed to run: "
                                       + "; ".join(describe(outs[k]) for k in bad)[:400])
                return
            want = self.want(scen, op) or {}
            wrong = [(k, want.get(k), o) for k, o in outs.items() if k not in want or not same_outcome(want[k], o)]
            detail = "; ".join(f"{k}: expected {describe(w)}, got {describe(o)}" for k, w, o in wrong[:3])
            self.g.check(label, not wrong, detail, core=self.is_core(scen, op))
            return
        if kind == "catalog":
            cat = eng.catalog()
            if op["against"].startswith("published:"):
                ref = self.shared.get(f"catalog:{op['against'].split(':', 1)[1]}")
                skip = set(op.get("exclude", []))
                if ref is None:
                    self.g.check(label, False, f"no {op['against']} schema to compare with (that scenario failed)",
                                 core=self.is_core(scen, op))
                    return
                diff = catalog_diff(strip_tables(ref, skip), strip_tables(cat, skip))
                if self.mode == "record" and diff:
                    raise RuntimeError(f"reference solution: {label}: schema differs from a new database: {diff[:4]}")
                self.g.check(label, not diff, "schema differs from a database built from scratch: " + "; ".join(diff[:4])
                             if diff else "", core=self.is_core(scen, op))
                return
            if op["against"].startswith("captured:"):
                ref = (state.get("captures") or {}).get(op["against"].split(":", 1)[1])
                diff = catalog_diff(ref, cat) if ref is not None else ["the captured schema is missing"]
                if self.mode == "record" and diff:
                    raise RuntimeError(f"reference solution: {label}: schema differs from {op['against']}: {diff[:4]}")
                self.g.check(label, not diff, "; ".join(diff[:4]), core=self.is_core(scen, op))
                return
            if op["against"] == "baseline":
                diff = catalog_diff(state["baseline_catalog"], cat)
                if self.mode == "record" and diff:
                    raise RuntimeError(f"reference solution: {label}: schema differs from the start: {diff[:4]}")
                self.g.check(label, not diff, "; ".join(diff[:4]), core=self.is_core(scen, op))
                return
            nt = self.norm_type()
            for req in self.sc.get("catalog", {}).get(op["against"], []):
                rname = f"{label}.{req.get('table') or req.get('view')}"
                probs = check_requirement(req, cat, nt)
                if self.mode == "record" and probs:
                    raise RuntimeError(f"reference solution: {rname}: {probs[:4]}")
                self.g.check(rname, not probs, "; ".join(probs[:4]), core=self.is_core(scen, op))
            return
        if kind == "locks":
            results = eng.judge_locks(state["evidence"], self.sc.get("lock_rules", {}))
            for rule, (ok, detail) in results.items():
                if self.mode == "record" and not ok:
                    raise RuntimeError(f"reference solution breaks lock rule {rule}: {detail}")
                self.g.check(f"{label}.{rule}", ok, detail, core=self.is_core(scen, op))
            return
        if kind in ("validate", "status", "idempotent"):
            fn = {"validate": "op_validate", "status": "op_status", "idempotent": "op_idempotent"}[kind]
            ok, detail, value = getattr(self, fn)(scen, op, eng, tool, state)
            if self.mode == "record":
                if not ok:
                    raise RuntimeError(f"reference solution: {label}: {detail}")
                self.store(scen, op, value)
                return
            self.g.check(label, ok, detail, core=self.is_core(scen, op))
            return
        raise RuntimeError(f"unknown scenario op {kind!r}")

    def history_check(self, eng, state):
        """Deployed changesets keep their rows (identity and execution type), and none of them was recorded again
        under another identity (a changeset that ran before must not run again)."""
        table = self.sc.get("tool_config", {}).get("changelog_table", "DATABASECHANGELOG")
        before = [r for r in (state.get("history_before") or []) if isinstance(r, list)]
        after = [r for r in eng.changelog_state(table) if isinstance(r, list)]

        def norm(path):
            return re.sub(r"^classpath:/?", "", str(path or ""))
        key = lambda r: (str(r[0]), str(r[1]), norm(r[2]))  # noqa: E731
        now = {key(r): r for r in after}
        lost = [f"{k[2]}::{k[0]}::{k[1]}" for k in (key(r) for r in before) if k not in now]
        changed = [f"{norm(r[2])}::{r[0]}::{r[1]} ({r[4]} -> {now[key(r)][4]})" for r in before
                   if key(r) in now and str(now[key(r)][4]) != str(r[4])]
        old_ids = {(str(r[0]), norm(r[2])) for r in before}
        old_keys = {key(r) for r in before}
        again = [f"{norm(r[2])}::{r[0]}::{r[1]}" for r in after if key(r) not in old_keys
                 and (str(r[0]), norm(r[2])) in old_ids]
        probs = []
        if lost:
            probs.append(f"{len(lost)} recorded changeset(s) disappeared from the history: {lost[:3]}")
        if changed:
            probs.append(f"recorded changesets changed execution type: {changed[:3]}")
        if again:
            probs.append(f"deployed changeset(s) were recorded again under another identity: {again[:3]}")
        return not probs, "; ".join(probs)

    def check_names(self, scen, op):
        label = self.key(scen, op)
        if op["op"] == "catalog" and op["against"] != "baseline":
            return [f"{label}.{r.get('table') or r.get('view')}" for r in self.sc.get("catalog", {}).get(op["against"], [])]
        if op["op"] in ("migrate", "rollback") and op.get("gate"):
            return []
        return [label]

    # -- history-tool ops (liquibase-style repair scenarios) --
    def op_validate(self, scen, op, eng, tool, state):
        res = tool.validate()
        return res.ok, ("" if res.ok else f"`{tool.name} validate` failed: {error_digest(res.output, 6)}"), None

    def op_status(self, scen, op, eng, tool, state):
        res = tool.status()
        pending = tool.pending(res.output) if hasattr(tool, "pending") else None
        ok = res.ok and pending == 0
        return ok, ("" if ok else f"`{tool.name} status`: {pending} change set(s) still pending: {error_digest(res.output, 6)}"), \
            pending

    def op_idempotent(self, scen, op, eng, tool, state):
        before = eng.history_fingerprint()
        cat0 = eng.catalog()
        res = tool.migrate(op.get("target"))
        after = eng.history_fingerprint()
        cat1 = eng.catalog()
        diff = catalog_diff(cat0, cat1)
        ok = res.ok and before == after and not diff
        why = (f"a second run failed (exit {res.code}): {tail(res.output, 4)}" if not res.ok else
               "a second run changed the history table" if before != after else
               f"a second run changed the schema: {diff[:3]}" if diff else "")
        return ok, why, None

    def run(self):
        try:
            if not self.file_gates():
                raise StopGrading("files")
            if self.sc.get("tool") == "alembic" and self.sc.get("graph"):
                self.alembic_graph_gate()
            for scen in self.sc["scenarios"]:
                if self.only and scen["name"] not in self.only:
                    continue
                self.run_scenario(scen)
        except StopGrading:
            pass
        return self.g

    def alembic_graph_gate(self):
        from dbm_tools import AlembicTool, prepare_repo
        root = self.work / "graph"
        if root.exists():
            shutil.rmtree(root)
        root.mkdir(parents=True)
        repo = prepare_repo(self.sub, root / "repo", self.solver_user)

        class _NoEngine:
            role, password = "x", "x"

            def tool_url(self, *_):
                return "postgresql+psycopg://x:x@127.0.0.1:1/x"

            def env_for_tools(self):
                return {}

            def terminate_app_sessions(self):
                pass
        tool = AlembicTool(repo, _NoEngine(), self.sc.get("tool_config"), self.solver_user)
        graph, err = tool.graph()
        if graph is None:
            self.g.gate("revision_graph", False, f"alembic could not load the migration scripts: {err}")
            return
        spec = self.sc["graph"]
        down = graph["down"]
        problems = []
        if len(graph["heads"]) != 1:
            problems.append(f"{len(graph['heads'])} heads {graph['heads']} (want exactly one)")

        def ancestors(rev):
            seen, todo = set(), [rev]
            while todo:
                r = todo.pop()
                for d in down.get(r, []):
                    if d not in seen:
                        seen.add(d)
                        todo.append(d)
            return seen
        chain = spec["targets"]
        for t in chain:
            if t not in down:
                problems.append(f"revision {t} does not exist")
        if not problems:
            if spec.get("base") and spec["base"] not in ancestors(chain[0]):
                problems.append(f"{chain[0]} does not descend from the deployed revision {spec['base']}")
            for a, b in zip(chain, chain[1:]):
                if a not in ancestors(b):
                    problems.append(f"{b} does not descend from {a}")
            if spec.get("last_is_head", True) and graph["heads"] != [chain[-1]]:
                problems.append(f"the head is {graph['heads']}, want {chain[-1]}")
        self.g.gate("revision_graph", not problems, "; ".join(problems[:4]))


def write_metrics(grading, out_dir, extra=None):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    reward = grading.reward()
    gate_failed = any(not g["ok"] for g in grading.gates.values())
    checks = {k: ({"ok": False, "detail": "not graded: a gate failed"} if gate_failed and v["ok"] else v)
              for k, v in grading.checks.items()}
    metrics = {"gates": grading.gates, "checks": checks,
               "passed_checks": sum(1 for c in grading.checks.values() if c["ok"]) if not gate_failed else 0,
               "total_checks": len(grading.checks), "core_checks": sorted(grading.core),
               "core_failed": sorted(c for c in grading.core if c in grading.checks and not grading.checks[c]["ok"]),
               "reward": reward, **(extra or {})}
    (out_dir / "metrics.json").write_text(json.dumps(metrics, indent=1))
    (out_dir / "reward.txt").write_text(f"{reward}\n")
    (out_dir / "reward.json").write_text(json.dumps({"reward": reward}))
    gate_line = " ".join(k + "=" + ("ok" if v["ok"] else "FAIL") for k, v in grading.gates.items())
    say(f"GATES {gate_line}")
    say(f"CHECKS {metrics['passed_checks']}/{metrics['total_checks']} passed; core failed: "
        f"{metrics['core_failed'] or 'none'}; reward {reward}")
    return metrics
